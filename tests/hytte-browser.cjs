const express = require('express');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { chromium } = require(path.join(process.env.TEMP, 'wishlist-multiuser-v1/node_modules/playwright'));
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hytte-browser-'));
  const app = express();
  app.use('/hytte', require('../hytte')({ dataFile: path.join(dir, 'data.json'), password: 'test-password', now: () => new Date('2026-10-10T14:00:00Z') }));
  const server = await new Promise(resolve => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)); });
  let browser;
  try {
    browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const base = `http://127.0.0.1:${server.address().port}/hytte/`;
    await page.goto(base);
    await page.getByRole('heading', { name: 'Book et opphold' }).waitFor();
    await page.getByLabel('Fullt navn').fill('Kari Nordmann');
    await page.getByLabel('Ankomst · kl. 15', { exact: true }).fill('2026-10-10');
    await page.getByLabel('Avreise · kl. 12', { exact: true }).fill('2026-10-12');
    assert.equal(await page.locator('#booking-form input[type=checkbox], #booking-form input[name=guests]').count(), 0);
    await page.getByRole('button', { name: 'Bekreft booking' }).click();
    await page.getByRole('heading', { name: 'God tur, Kari Nordmann!' }).waitFor();
    const code = await page.locator('.receipt code').innerText();
    assert.match(code, /^[0-9]{6}$/);
    await page.screenshot({ path: 'artifacts/hytte-desktop.png', fullPage: true });
    await page.getByRole('link', { name: 'Åpne mitt besøk' }).click();
    await page.getByRole('button', { name: 'Hent besøk' }).click();
    await page.getByRole('heading', { name: 'Sjekkliste ved ankomst' }).waitFor();
    for (const radio of await page.locator('#checklist-form input[value=yes]').all()) await radio.check();
    await page.getByRole('button', { name: 'Registrer ankomst', exact: false }).click();
    await page.getByRole('heading', { name: 'Sjekkliste ved avreise' }).waitFor();
    for (const radio of await page.locator('#checklist-form input[value=yes]').all()) await radio.check();
    await page.getByRole('button', { name: 'Registrer avreise og avslutt besøket' }).click();
    await page.getByRole('heading', { name: 'Takk for at du tok vare på hytta!' }).waitFor();
    await page.goto(base + 'admin');
    await page.getByLabel('Administratorpassord').fill('test-password');
    await page.getByRole('button', { name: 'Logg inn' }).click();
    await page.getByRole('heading', { name: 'Bookinger og alle besøk' }).waitFor();
    await page.locator('summary').click();
    assert.equal(await page.locator('.admin-visit-code').innerText(), code);
    assert.equal(await page.locator('.brand').innerText(), 'Geostrøm AS\nFirmahytta');
    assert.equal(await page.locator('.hero').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(32, 59, 43)');
    await page.getByRole('heading', { name: /Avreise ·/ }).waitFor();
    await page.locator('textarea[name=arrival]').fill('Har du sjekket hytta?');
    await page.getByRole('button', { name: 'Lagre spørsmål' }).click();
    await page.getByRole('status').filter({ hasText: 'Spørsmålene er lagret.' }).waitFor();
    await page.screenshot({ path: 'artifacts/hytte-admin.png', fullPage: true });
    page.on('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Fjern booking' }).click();
    await page.locator('.pill.cancelled').waitFor();
    await page.goto(base);
    await page.getByRole('heading', { name: 'Book et opphold' }).waitFor();
    assert.equal(await page.locator('.stay').count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'artifacts/hytte-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile page must not overflow horizontally');
    assert.deepEqual(errors, []);
    console.log('PASS: desktop and mobile, booking receipt, arrival, departure, admin login, history, question edit, cancellation, no JS errors.');
  } finally { if (browser) await browser.close(); server.close(); fs.rmSync(dir, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });

